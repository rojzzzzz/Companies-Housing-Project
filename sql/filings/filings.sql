CREATE TABLE IF NOT EXISTS staging.filings (
    company_number INT NOT NULL,
    transaction_id TEXT NOT NULL,
    barcode VARCHAR(15),
    type VARCHAR(15) NOT NULL,
    date DATE NOT NULL,
    category TEXT NOT NULL,
    subcategory TEXT,
    description TEXT,
    pages NUMERIC,
    paper_filed BOOLEAN,
    action_date DATE,
    description_value TEXT,
    change_date DATE,
    officer_name TEXT,
    appointment_date DATE,
    new_date DATE,
    date_value TEXT,
    old_address TEXT,
    new_address TEXT,
    termination_date DATE,
    made_up_date DATE,
    link_self TEXT,
    document_metadata TEXT,
    PRIMARY KEY (company_number, transaction_id)
);